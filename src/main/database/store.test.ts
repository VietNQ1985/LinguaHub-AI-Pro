import { test, expect } from 'vitest'
import { mkdtemp, rm, mkdir } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { resolve, join } from 'node:path'
import { createLearningStore } from './store'
test('disk write failure prevents using unsaved in-memory changes',async()=>{
  const directory=await mkdtemp(join(tmpdir(),'linguahub-failure-'))
  try{
    const store=await createLearningStore(directory,resolve('node_modules/sql.js/dist/sql-wasm.wasm'))
    await mkdir(join(directory,'learning.sqlite.tmp'))
    await expect(store.add({term:'test',meaning:'Kiểm thử'})).rejects.toThrow()
    expect(()=>store.list()).toThrow('Lưu dữ liệu thất bại')
    await expect(store.add({term:'another',meaning:'Khác'})).rejects.toThrow('Lưu dữ liệu thất bại')
  }finally{await rm(directory,{recursive:true,force:true})}
})
test('Vietnamese vocabulary and review schedule survive database reload', async()=>{
  const directory = await mkdtemp(join(tmpdir(),'linguahub-test-'))
  try {
    const wasm = resolve('node_modules/sql.js/dist/sql-wasm.wasm')
    const store = await createLearningStore(directory,wasm)
    expect(store.getNotificationPreferences()).toEqual({whatsapp:false,teams:false,zalo:false})
    expect(store.getManualCloudConsent()).toBe(false)
    expect(store.getReasoningEffort()).toBe('max')
    expect(store.getTranslationReasoningEffort()).toBe('low')
    expect(store.getFastMode()).toBe(false)
    await store.setNotificationPreference('whatsapp',true)
    await store.setManualCloudConsent(true)
    await store.add({term:'reconciliation',meaning:'Đối soát công nợ'})
    await store.setPreferences({theme:'light',model:'local-test'})
    await store.setReasoningEffort('high')
    await store.setTranslationReasoningEffort('xhigh')
    await store.setFastMode(true)
    await store.setPanelWidth(410)
    await expect(store.setRetentionDays(90)).resolves.toBe(90)
    const word = store.list()[0]
    await store.review(word.id,true)
    await store.recordAiUsage('ollama','translate')
    await store.recordAiUsage('chatgpt','reply')
    expect(store.getLearningProgress()).toMatchObject({totalWords:1,reviewedWords:1,dueWords:0,reviewsToday:1})
    expect(store.getLearningProgress()).toMatchObject({aiRequestsToday:2,ollamaRequestsToday:1,chatgptRequestsToday:1})
    await expect(store.completeDailyLesson()).resolves.toBe(true)
    await expect(store.completeDailyLesson()).resolves.toBe(false)
    const reopened = await createLearningStore(directory,wasm)
    expect(reopened.getNotificationPreferences()).toEqual({whatsapp:true,teams:false,zalo:false})
    expect(reopened.getManualCloudConsent()).toBe(true)
    expect(reopened.getReasoningEffort()).toBe('high')
    expect(reopened.getTranslationReasoningEffort()).toBe('xhigh')
    expect(reopened.getFastMode()).toBe(true)
    expect(reopened.getPreferences()).toEqual({theme:'light',model:'local-test',panelWidth:410})
    expect(reopened.getRetentionDays()).toBe(90)
    expect(reopened.list()[0].meaning).toBe('Đối soát công nợ')
    expect(reopened.list()[0].dueAt).toBeGreaterThan(Date.now())
    expect(reopened.getLearningProgress()).toMatchObject({totalWords:1,reviewedWords:1,reviewsToday:1,lessonsToday:1,lessonCompletedToday:true,studyStreak:1,aiRequestsToday:2,ollamaRequestsToday:1,chatgptRequestsToday:1})
    await expect(reopened.setPanelWidth(200)).rejects.toThrow()
    await expect(reopened.setManualCloudConsent('yes')).rejects.toThrow()
    await expect(reopened.setReasoningEffort('turbo')).rejects.toThrow()
    await expect(reopened.setTranslationReasoningEffort('turbo')).rejects.toThrow()
    await expect(reopened.setFastMode('yes')).rejects.toThrow()
    await expect(reopened.setRetentionDays(10)).rejects.toThrow()
    await expect(reopened.add({term:'',meaning:''})).rejects.toThrow()
    await reopened.clearVocabulary()
    const cleared=await createLearningStore(directory,wasm)
    expect(cleared.list()).toHaveLength(0)
    expect(cleared.getLearningProgress()).toMatchObject({totalWords:0,reviewsToday:0,lessonsToday:0,studyStreak:0})
    expect(cleared.getPreferences().model).toBe('local-test')
    expect(cleared.getReasoningEffort()).toBe('high')
    expect(cleared.getTranslationReasoningEffort()).toBe('xhigh')
    expect(cleared.getFastMode()).toBe(true)
  } finally { await rm(directory,{recursive:true,force:true}) }
})
test('clearAll removes local learning data, activity, and saved preferences',async()=>{
  const directory=await mkdtemp(join(tmpdir(),'linguahub-clear-all-'))
  try{
    const store=await createLearningStore(directory,resolve('node_modules/sql.js/dist/sql-wasm.wasm'))
    await store.add({term:'go-live',meaning:'Chính thức vận hành'})
    await store.completeDailyLesson()
    await store.setNotificationPreference('teams',true)
    await store.setManualCloudConsent(true)
    await store.setPreferences({theme:'light',model:'chatgpt:gpt-test'})
    await store.clearAll()
    expect(store.list()).toEqual([])
    expect(store.getLearningProgress()).toMatchObject({totalWords:0,reviewsToday:0,lessonsToday:0})
    expect(store.getNotificationPreferences()).toEqual({whatsapp:false,teams:false,zalo:false})
    expect(store.getManualCloudConsent()).toBe(false)
    expect(store.getPreferences()).toEqual({theme:'light',model:'',panelWidth:360})
    expect(store.getRetentionDays()).toBe(0)
    expect(store.getReasoningEffort()).toBe('max')
    expect(store.getTranslationReasoningEffort()).toBe('low')
    expect(store.getFastMode()).toBe(false)
  }finally{await rm(directory,{recursive:true,force:true})}
})
